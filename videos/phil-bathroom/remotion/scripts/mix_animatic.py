"""Temp animatic mix: locked narration + Codex temp SFX re-placed onto the fitted cut.

usage: python scripts/mix_animatic.py   (needs numpy + soundfile)
in : ../narration/voice.wav, ../assets/audio/sfx/*.wav, ../assets/audio/cues.md, src/timing.json
out: ../assets/audio/mix_animatic.wav (48 kHz mono, exactly TOTAL frames long) + ../assets/audio/mix_animatic_cues.md
Cue frames in cues.md are SHOTLIST design frames; each is remapped proportionally into its fitted shot (S16 exact).
Levels follow SKILL.md (SFX -6 dB, voice unchanged); the S16 punchline cue sits at -3 dB so it reads on a phone.
"""
import json, re, os
import numpy as np, soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__))
EP = os.path.normpath(os.path.join(HERE, "..", ".."))
SR = 48000
timing = json.load(open(os.path.join(HERE, "..", "src", "timing.json")))
shots = {s["id"]: s for s in timing["shots"]}
n_out = round(timing["total"] / timing["fps"] * SR)

def load(p):
    y, sr = sf.read(p, dtype="float32")
    y = y if y.ndim == 1 else y.mean(1)
    if sr != SR:
        raise SystemExit(f"{p}: {sr} Hz (expected {SR})")
    return y

def fitted(shot, frame):
    s = shots[shot]
    if shot == "S16":  # supplied clips start after the close-up pre-roll; the room tone starts at the cut
        return s["from"] if frame == s["designFrom"] else s["from"] + timing["s16Pre"] + (frame - s["designFrom"])
    k = (s["to"] - s["from"]) / (s["designTo"] - s["designFrom"])
    return s["from"] + round((frame - s["designFrom"]) * k)

out = np.zeros(n_out, dtype=np.float32)
voice = load(os.path.join(EP, "narration", "voice.wav"))
off = round(timing.get("voiceOffsetFrames", 0) / timing["fps"] * SR)
out[off:off + len(voice)] += voice[: n_out - off]

rows, report = [], ["| File | Shot | Design frame | Fitted frame | Time (s) | Gain dB |", "| --- | --- | ---: | ---: | ---: | ---: |"]
for line in open(os.path.join(EP, "assets", "audio", "cues.md")):
    m = re.match(r"\|\s*(S\d\d_[\w.]+\.wav)\s*\|\s*(S\d\d)\s*\|\s*(\d+)\s*\|", line)
    if m:
        rows.append((m.group(1), m.group(2), int(m.group(3))))
# S15_sigh is dropped since 2026-11-19: the narrator now sighs at the top of S16 (owner note) and two sighs would clash
SKIP = {"S15_sigh.wav"}
for name, shot, frame in rows:
    if name in SKIP:
        report.append(f"| {name} | {shot} | {frame} | — | — | dropped (narrator sighs in S16) |")
        continue
    y = load(os.path.join(EP, "assets", "audio", "sfx", name))
    f = fitted(shot, frame)
    gain = -3.0 if name == "S16_fart.wav" else -6.0
    a = round(f / timing["fps"] * SR)
    b = min(n_out, a + len(y))
    out[a:b] += y[: b - a] * 10 ** (gain / 20)
    report.append(f"| {name} | {shot} | {frame} | {f} | {f / timing['fps']:.2f} | {gain:+.0f} |")

# final 5 frames are a black edit: let only the fart tail ring into them, then fade to silence at the very end
fade = round(0.08 * SR)
out[-fade:] *= np.linspace(1, 0, fade, dtype=np.float32)
peak = float(np.abs(out).max())
if peak > 0.97:
    out *= 0.97 / peak
dst = os.path.join(EP, "assets", "audio", "mix_animatic.wav")
sf.write(dst, out, SR, subtype="PCM_24")
open(os.path.join(EP, "assets", "audio", "mix_animatic_cues.md"), "w").write(
    "# Animatic temp mix — fitted cue placements\n\nGenerated by `remotion/scripts/mix_animatic.py` from `cues.md` + `remotion/src/timing.json`.\n\n" + "\n".join(report) + "\n")
print(f"{dst}: {n_out / SR:.2f}s, {len(rows)} cues, peak {20 * np.log10(max(peak, 1e-9)):.1f} dBFS (pre-limit)")
fart = [r for r in report if "fart" in r]
print("fart:", fart[0] if fart else "MISSING")
